import Foundation
import Nats

extension JetStreamContext {

    /// Publishes a message on a stream subject without waiting for the acknowledgement from the server.
    /// Acknowledgements of all publishes are received on a single subscription and can be awaited with
    /// ``AckFuture/wait()``, or all at once with ``publishAsyncComplete()``.
    ///
    /// - Parameters:
    ///   - subject: Subject on which the message will be published.
    ///   - message: NATS message payload.
    ///   - headers:Optional set of message headers.
    ///   - options: Optional message deduplication and optimistic concurrency expectations.
    ///
    /// - Returns: ``AckFuture`` allowing to await for the ack from the server.
    public func publish(
        _ subject: String, message: Data, headers: NatsHeaderMap? = nil,
        options: PublishOptions? = nil
    ) async throws -> AckFuture {
        let headers =
            if let options { options.apply(to: headers ?? NatsHeaderMap()) } else { headers }
        let (reply, pending) = try await publisher.register()
        let publish: @Sendable () async throws -> Void = { [client] in
            try await client.publish(message, subject: subject, reply: reply, headers: headers)
        }
        do {
            try await publish()
        } catch {
            await publisher.remove(reply)
            throw error
        }
        return AckFuture(
            publisher: publisher, reply: reply, pending: pending, timeout: self.timeout,
            retryAttempts: options?.retryAttempts ?? PublishOptions.defaultRetryAttempts,
            retryWait: options?.retryWait ?? PublishOptions.defaultRetryWait, republish: publish)
    }
}

/// Options used to deduplicate a published message and to set optimistic concurrency expectations.
/// If an expectation is not met, ``AckFuture/wait()`` throws ``JetStreamError/PublishError``.
public struct PublishOptions: Sendable {
    /// Unique ID used by the stream to discard duplicates within its duplicate window.
    public var messageId: String?
    /// Name of the stream the message is expected to be stored in.
    public var expectedStream: String?
    /// Expected sequence of the last message in the stream.
    public var expectedLastSequence: UInt64?
    /// Expected sequence of the last message on the published subject.
    public var expectedLastSubjectSequence: UInt64?
    /// Expected message ID of the last message in the stream.
    public var expectedLastMessageId: String?
    /// Subject (may contain wildcards) ``expectedLastSubjectSequence`` is checked against,
    /// instead of the published subject.
    public var expectedLastSubjectSequenceSubject: String?
    /// Per-message TTL, requires ``StreamConfig/allowMsgTTL``.
    public var ttl: MessageTTL?
    /// Schedule on which the message is delivered to ``scheduleTarget``,
    /// requires ``StreamConfig/allowMsgSchedules``.
    public var schedule: MessageSchedule?
    /// Subject on which scheduled messages are delivered.
    public var scheduleTarget: String?
    /// Subject whose latest message is delivered on schedule instead of the published payload.
    public var scheduleSource: String?
    /// TTL of messages generated by the scheduler, requires ``StreamConfig/allowMsgTTL``.
    public var scheduleTTL: MessageTTL?
    /// Each scheduled delivery replaces the previous message on ``scheduleTarget``.
    public var scheduleRollup: Bool
    /// Number of times the message is republished if no stream responded (e.g. during a leader election).
    public var retryAttempts: Int
    /// Time to wait between retries.
    public var retryWait: TimeInterval

    /// Default number of retries when no stream responds.
    public static let defaultRetryAttempts = 2
    /// Default time between retries.
    public static let defaultRetryWait: TimeInterval = 0.25

    /// Creates a value with the given properties, see the properties of the same name.
    public init(
        messageId: String? = nil, expectedStream: String? = nil,
        expectedLastSequence: UInt64? = nil, expectedLastSubjectSequence: UInt64? = nil,
        expectedLastMessageId: String? = nil, expectedLastSubjectSequenceSubject: String? = nil,
        ttl: MessageTTL? = nil, schedule: MessageSchedule? = nil, scheduleTarget: String? = nil,
        scheduleSource: String? = nil, scheduleTTL: MessageTTL? = nil,
        scheduleRollup: Bool = false, retryAttempts: Int = PublishOptions.defaultRetryAttempts,
        retryWait: TimeInterval = PublishOptions.defaultRetryWait
    ) {
        self.messageId = messageId
        self.expectedStream = expectedStream
        self.expectedLastSequence = expectedLastSequence
        self.expectedLastSubjectSequence = expectedLastSubjectSequence
        self.expectedLastMessageId = expectedLastMessageId
        self.expectedLastSubjectSequenceSubject = expectedLastSubjectSequenceSubject
        self.ttl = ttl
        self.schedule = schedule
        self.scheduleTarget = scheduleTarget
        self.scheduleSource = scheduleSource
        self.scheduleTTL = scheduleTTL
        self.scheduleRollup = scheduleRollup
        self.retryAttempts = retryAttempts
        self.retryWait = retryWait
    }

    internal func apply(to headers: NatsHeaderMap) -> NatsHeaderMap {
        var headers = headers
        if let messageId {
            headers.insert(.natsMsgId, NatsHeaderValue(messageId))
        }
        if let expectedStream {
            headers.insert(.natsExpectedStream, NatsHeaderValue(expectedStream))
        }
        if let expectedLastSequence {
            headers.insert(.natsExpectedLastSequence, NatsHeaderValue(String(expectedLastSequence)))
        }
        if let expectedLastSubjectSequence {
            headers.insert(
                .natsExpectedLastSubjectSequence,
                NatsHeaderValue(String(expectedLastSubjectSequence)))
        }
        if let expectedLastMessageId {
            headers.insert(.natsExpectedLastMsgId, NatsHeaderValue(expectedLastMessageId))
        }
        if let expectedLastSubjectSequenceSubject {
            headers.insert(
                .natsExpectedLastSubjectSequenceSubject,
                NatsHeaderValue(expectedLastSubjectSequenceSubject))
        }
        if let ttl {
            headers.insert(.natsTTL, NatsHeaderValue(ttl.headerValue))
        }
        if let schedule {
            headers.insert(.natsSchedule, NatsHeaderValue(schedule.headerValue))
            if case .cron(_, let timeZone?) = schedule {
                headers.insert(.natsScheduleTimeZone, NatsHeaderValue(timeZone))
            }
        }
        if let scheduleTarget {
            headers.insert(.natsScheduleTarget, NatsHeaderValue(scheduleTarget))
        }
        if let scheduleSource {
            headers.insert(.natsScheduleSource, NatsHeaderValue(scheduleSource))
        }
        if let scheduleTTL {
            headers.insert(.natsScheduleTTL, NatsHeaderValue(scheduleTTL.headerValue))
        }
        if scheduleRollup {
            headers.insert(.natsScheduleRollup, NatsHeaderValue("sub"))
        }
        return headers
    }
}

/// Time to live of a message.
public enum MessageTTL: Equatable, Sendable {
    /// The message expires after the given time interval (at least 1 second).
    case after(TimeInterval)
    /// The message never expires, regardless of the stream `maxAge`.
    case never

    internal var headerValue: String {
        switch self {
        case .after(let interval):
            return "\(Int64((interval * 1000).rounded()))ms"
        case .never:
            return "never"
        }
    }
}

/// Schedule of a message published with ``PublishOptions/schedule``.
public enum MessageSchedule: Equatable, Sendable {
    /// One-time delivery at the given date.
    case at(Date)
    /// Repeated delivery at the given interval (at least 1 second).
    case every(TimeInterval)
    /// Delivery according to a 6-field cron expression (with seconds) or a predefined schedule
    /// such as `@hourly`, optionally in the given IANA time zone.
    case cron(String, timeZone: String? = nil)

    internal var headerValue: String {
        switch self {
        case .at(let date):
            let formatter = ISO8601DateFormatter()
            formatter.timeZone = TimeZone(identifier: "UTC")
            return "@at \(formatter.string(from: date))"
        case .every(let interval):
            return "@every \(Int64((interval * 1000).rounded()))ms"
        case .cron(let expression, _):
            return expression
        }
    }
}

/// The pending acknowledgement of a published message, returned by
/// ``JetStreamContext/publish(_:message:headers:options:)``.
public struct AckFuture: Sendable {
    let publisher: AsyncPublisher
    let reply: String
    let pending: PendingAck
    let timeout: TimeInterval
    var retryAttempts = 0
    var retryWait: TimeInterval = 0
    var republish: (@Sendable () async throws -> Void)? = nil

    /// Waits for an ACK from JetStream server.
    /// If no stream responded, the message is republished according to ``PublishOptions/retryAttempts``.
    ///
    /// - Returns: Acknowledgement object returned by the server.
    ///
    /// > **Throws:**
    /// > - ``JetStreamError/RequestError`` if the request timed out (client did not receive the ack in time) or
    /// > - ``JetStreamError/PublishError`` if the message was rejected or there is no stream on the subject.
    public func wait() async throws -> Ack {
        do {
            let ack = try await waitForAck()
            await publisher.remove(reply)
            return ack
        } catch {
            await publisher.remove(reply)
            throw error
        }
    }

    private func waitForAck() async throws -> Ack {
        var attempt = 0
        var response = try await nextResponse()
        while response.status == StatusCode.noResponders, attempt < retryAttempts,
            let republish
        {
            attempt += 1
            try await Task.sleep(nanoseconds: UInt64(retryWait * 1_000_000_000))
            await publisher.reregister(reply, pending)
            try await republish()
            response = try await nextResponse()
        }
        if response.status == StatusCode.noResponders {
            throw JetStreamError.PublishError.streamNotFound
        }

        let decoder = JSONDecoder()
        guard let payload = response.payload else {
            throw JetStreamError.RequestError.emptyResponsePayload
        }

        let ack = try decoder.decode(Response<Ack>.self, from: payload)
        switch ack {
        case .success(let ack):
            return ack
        case .error(let err):
            if let publishErr = JetStreamError.PublishError(from: err.error) {
                throw publishErr
            } else {
                throw err.error
            }
        }
    }

    private func nextResponse() async throws -> NatsMessage {
        let pending = pending
        let timeout = Task {
            try await Task.sleep(nanoseconds: UInt64(self.timeout * 1_000_000_000))
            pending.resolve(.failure(JetStreamError.RequestError.timeout))
        }
        defer { timeout.cancel() }
        return try await pending.value()
    }
}

/// The acknowledgement of a message stored in a stream.
public struct Ack: Codable, Sendable {
    /// The stream the message was stored in.
    public let stream: String
    /// The sequence of the message in the stream.
    public let seq: UInt64
    /// The JetStream domain of the stream.
    public let domain: String?
    /// Indicates whether the message was a duplicate and was not stored again.
    public let duplicate: Bool

    // Custom CodingKeys to map JSON keys to Swift property names
    enum CodingKeys: String, CodingKey {
        case stream
        case seq
        case domain
        case duplicate
    }

    // Custom initializer from Decoder
    public init(from decoder: Decoder) throws {
        let container = try decoder.container(keyedBy: CodingKeys.self)
        // Decode `stream` and `seq` as they are required
        stream = try container.decode(String.self, forKey: .stream)
        seq = try container.decode(UInt64.self, forKey: .seq)

        // Decode `domain` as optional since it may not be present
        domain = try container.decodeIfPresent(String.self, forKey: .domain)

        // Decode `duplicate` and provide a default value of `false` if not present
        duplicate = try container.decodeIfPresent(Bool.self, forKey: .duplicate) ?? false
    }
}
